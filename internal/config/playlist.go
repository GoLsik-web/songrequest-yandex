package config

// Цена награды за плейлист.
//
// Правило владельца: плейлист должен быть «чуть выгодней, чем заказывать треки
// по отдельности», и это «чуть» надо уметь менять. Поэтому цена не вписывается
// руками, а считается: цена одного трека, умноженная на число треков в
// плейлисте, минус скидка.
//
// Так она сама едет следом за настройками. Поднял цену трека — плейлист
// подорожал; разрешил в плейлисте не пять треков, а восемь — плейлист
// подорожал ровно на три трека со скидкой. Вписанная руками цена через неделю
// таких правок разошлась бы с поштучной и стала бы либо подарком, либо
// грабежом, а заметил бы это стример не сразу.
//
// Своя цена всё-таки возможна (PlaylistCost): бывает, что круглое число просто
// красивее. Тогда считалка молчит.

// PlaylistTrackCount — сколько треков берём из плейлиста.
func (c Config) PlaylistTrackCount() int {
	n := c.PlaylistMaxTracks
	if n < 1 {
		return 5
	}
	// Верхний предел не придирка. Плейлист занимает эфир целиком: двадцать
	// треков по три с половиной минуты — это час чужой музыки подряд, и
	// одобрять такое стример будет ровно один раз.
	if n > 20 {
		return 20
	}
	return n
}

// PlaylistDiscountPercent — скидка на плейлист в процентах.
func (c Config) PlaylistDiscountPercent() int {
	d := c.PlaylistDiscount
	if d < 0 {
		return 0
	}
	// Больше девяноста процентов — это уже не скидка, а раздача: заказ
	// плейлиста стал бы дешевле одного трека, и поштучные заказы просто
	// перестали бы существовать.
	if d > 90 {
		return 90
	}
	return d
}

// PlaylistPrice — сколько баллов стоит плейлист.
func (c Config) PlaylistPrice() int {
	if c.PlaylistCost > 0 {
		return c.PlaylistCost
	}

	full := c.RewardCost * c.PlaylistTrackCount()
	price := full * (100 - c.PlaylistDiscountPercent()) / 100

	// Плейлист не может стоить дешевле одного трека: иначе выгоднее заказать
	// плейлист из одной песни, чем саму песню, и обычная награда обесценится.
	if price < c.RewardCost {
		price = c.RewardCost
	}
	// Twitch не принимает награду дешевле балла.
	if price < 1 {
		price = 1
	}
	return price
}

// PlaylistPricePerTrack — во сколько плейлист выходит за трек. Для подписи в
// панели: стример должен видеть, что он предлагает зрителю, а не верить слову
// «скидка».
func (c Config) PlaylistPricePerTrack() int {
	n := c.PlaylistTrackCount()
	if n < 1 {
		return c.PlaylistPrice()
	}
	return c.PlaylistPrice() / n
}
