// Package desktop превращает приложение из «сервера, который надо открыть во
// вкладке» в обычную программу Windows: своё окно с панелью внутри и значок
// возле часов.
//
// Зачем. Раньше запуск выглядел так: чёрное окно консоли, которое нельзя
// закрывать, плюс вкладка браузера, плюс отдельная программа обхода
// блокировок. Друг-тестер назвал это «бешеное количество вкладок». Теперь
// запущена одна программа: закрыл крестиком — она ушла к часам и продолжает
// принимать заказы, вышел через значок — закрылась целиком.
//
// Внутри окна тот же самый адрес 127.0.0.1, что и раньше: панель не переписана,
// она просто показана не в браузере, а в окне через WebView2 — движок Edge,
// который уже стоит в Windows 10 и 11. Если его вдруг нет, приложение не
// падает, а открывает панель в браузере, как делало до этого шага.
package desktop

import (
	_ "embed"
	"os"
	"path/filepath"
)

// iconICO — значок приложения для окна и трея. Рисуется программой
// tools/ico из того же макета, что web/favicon.svg.
//
//go:embed icon.ico
var iconICO []byte

// Geometry — размер и положение окна, чтобы они пережили перезапуск.
//
// Хранится в настройках, а не вычисляется заново: стример один раз растянул
// окно под свой экран, и каждый следующий запуск обязан открыться так же.
type Geometry struct {
	X, Y          int
	Width, Height int
	Maximized     bool
}

// Options — всё, что окну нужно знать о приложении.
type Options struct {
	// URL — адрес панели, тот же, что открывался в браузере.
	URL string
	// Title — заголовок окна.
	Title string
	// IconPath — путь к .ico на диске. Пусто — окно останется с общим
	// значком Windows.
	IconPath string
	// DataPath — куда WebView2 сложит свои временные файлы. Без этого он
	// заводит папку рядом с .exe, а .exe у стримера лежит в «Загрузках».
	DataPath string
	// Geometry — с каким размером открыться. Нули означают «как по умолчанию».
	Geometry Geometry
	// OnGeometry зовётся, когда человек подвигал или закрыл окно. Сохранять
	// на диск здесь же не нужно — вызов идёт из потока окна.
	OnGeometry func(Geometry)
	// OnExternal — открыть ссылку во внешнем браузере. Вход в Spotify и
	// Twitch остаётся в обычном браузере: страницы входа тяжёлые, а в
	// маленьком окне без адресной строки человек не поймёт, куда попал.
	OnExternal func(url string)
	// SystemFrame оставляет окну обычную полосу заголовка Windows вместо
	// нашей. Запасной путь на случай, если со своей полосой что-то пойдёт не
	// так на чужой Windows: флаг -рамка-windows.
	SystemFrame bool
	// OnHide зовётся, когда окно спряталось в трей: панель об этом стоит
	// сказать в лог, иначе «программа пропала» выглядит как поломка.
	OnHide func()
}

// IconFile кладёт значок рядом с настройками и возвращает путь к нему.
//
// Значок вшит в .exe, но и окну, и трею Windows отдаёт значок только файлом
// или ресурсом, поэтому его приходится один раз выложить на диск. Пишем в
// папку данных, а не во временную: временную чистят уборщики диска прямо на
// ходу, и значок пропадал бы посреди стрима.
func IconFile(dir string) (string, error) {
	path := filepath.Join(dir, "icon.ico")
	// Переписываем только если файла нет или он другой: лишняя запись при
	// каждом запуске изнашивает диск и мешает Windows кэшировать значок.
	if old, err := os.ReadFile(path); err == nil && len(old) == len(iconICO) {
		return path, nil
	}
	if err := os.WriteFile(path, iconICO, 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// AuthOptions — отдельное окно для входа в чужой сервис (пока только Spotify).
//
// Зачем оно вообще нужно. Страницу входа Spotify открывает браузер, а браузер
// про обход блокировок внутри приложения ничего не знает: из России она у него
// просто не откроется. Раньше это лечилось просьбой «включи VPN на время
// первого входа» — то есть человеку всё равно приходилось держать рядом ту
// самую программу обхода, ради избавления от которой всё и затевалось.
//
// Это окно ходит через наш же обход и закрывается само, как только Spotify
// вернул нас на 127.0.0.1.
type AuthOptions struct {
	// URL — страница входа.
	URL string
	// Title — заголовок окна.
	Title string
	// IconPath — путь к .ico (см. IconFile).
	IconPath string
	// DataPath — своя папка для WebView2, обязательно отдельная от окна
	// панели: движок делит один браузер на все окна с общей папкой, и тогда
	// окно входа получило бы настройки соединения от панели, а не свои.
	DataPath string
	// Proxy — через кого ходить: socks5://127.0.0.1:порт. Пусто — напрямую.
	Proxy string
	// DonePath — адрес, на который сервис возвращает после входа. Дошли до
	// него — окно закрывается само.
	DonePath string
	// OnURL видит адрес каждой открытой страницы. true — вход закончен, окно
	// закрывается. Так забирается токен, который Яндекс кладёт в адрес.
	OnURL func(url string) bool
	// OnDone зовётся, когда окно закрылось.
	OnDone func()
}

// TrayOptions — значок возле часов и его меню.
type TrayOptions struct {
	// IconPath — путь к .ico на диске (см. IconFile).
	IconPath string
	// Tooltip — подсказка, которая всплывает над значком.
	Tooltip string
	// WidgetURL — адрес виджета для OBS. Его кладём в буфер обмена по пункту
	// меню: в OBS этот адрес вставляют руками, а панель ради одного адреса
	// открывать незачем.
	WidgetURL string
	// OnOpen — показать окно панели (левый клик и пункт меню).
	OnOpen func()
	// OnCopy — чем кончилась попытка положить адрес в буфер обмена.
	OnCopy func(err error)
	// OnQuit — выйти из программы совсем.
	OnQuit func()
}
