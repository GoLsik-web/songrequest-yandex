package player

import (
	"context"
	"time"

	"songrequest-yandex/internal/queue"
	"songrequest-yandex/internal/yandex"
)

// Ожидание конца текущего трека.
//
// Раньше заказ включался немедленно и обрывал то, что играло у стримера, на
// середине. Для зрителей это выглядело как «кто-то заказал — и музыка резко
// переключилась»; для стримера — как будто приложение перебивает его самого.
//
// Теперь заказ ждёт. Порядок такой:
//
//	заказ встал в очередь → текущий трек доигрывает до конца →
//	Spotify сам переходит к следующему треку плейлиста →
//	вот в этот момент делается снимок → играет заказ →
//	очередь опустела → возврат на тот самый следующий трек
//
// Момент снимка здесь принципиален. Снимать надо не тогда, когда заказ
// пришёл, а тогда, когда трек уже доиграл: иначе возврат приведёт обратно на
// трек, который зрители только что дослушали целиком, и он заиграет второй
// раз. А так Spotify сам переводит стрелку на следующий трек, и снимок
// запоминает уже его — возврат получается ровно там, где музыка и была бы,
// если бы заказа не случилось.

// waitTail — последний отрезок трека, который досыпается точно, без
// промежуточных проверок. Три секунды: за это время позиция, которую отдаёт
// Spotify, ещё не успевает заметно уплыть, а лишних запросов уже нет.
const waitTail = 3 * time.Second

// settle — сколько ждём после конца трека, прежде чем включать заказ.
//
// Ноль здесь не годится, хотя и кажется идеалом. Сразу после ожидания
// делается снимок — то место, куда музыка вернётся после заказов. Если снять
// его ровно в миг переключения, Spotify ещё покажет доигравший трек А, и
// возврат приведёт на него: зрители услышат его второй раз подряд.
//
// Полсекунды хватает, чтобы Spotify перевёл стрелку на следующий трек. Ровно
// столько его и слышно перед заказом — против прежних двух секунд, когда мы
// узнавали о конце трека только увидев следующий.
const settle = 500 * time.Millisecond

// waitForOwnTrack ждёт, пока доиграет то, что стример слушает сам.
//
// Возвращает управление сразу, если играть нечего, если играет не Spotify,
// или если ждать запретили настройкой. Скип и отмена прерывают ожидание:
// стример всегда может сказать «хватит, включай».
func (p *Player) waitForOwnTrack(ctx context.Context, item queue.Item) {
	if _, wait := p.options(); !wait {
		return
	}

	// Ждём конкретный трек — тот, что звучал в момент заказа. Без этого
	// ожидание перескакивает на следующий трек плейлиста и залипает навсегда:
	// «пока что-нибудь играет» на живом плейлисте не кончается никогда.
	var waitingFor string

	// О самом ожидании надо сказать вслух, и один раз. Молчаливая пауза в
	// три минуты между «заказ принят» и первым звуком неотличима от
	// зависания — с этого начинались все жалобы «ничего не работает».
	told := false

	for ctx.Err() == nil {
		st, ok, err := p.music.State(ctx)
		if err != nil || !ok || st == nil || st.Item == nil || !st.IsPlaying {
			// Ничего не играет, либо Spotify не отвечает. Ждать нечего.
			return
		}

		if waitingFor == "" {
			waitingFor = st.Item.URI
		} else if !yandex.SameTrack(st.Item.URI, waitingFor) {
			// Трек сменился — значит тот, которого мы ждали, доиграл.
			p.log.Info("трек стримера доиграл, включаю заказ")
			return
		}

		left := time.Duration(st.Item.DurationMs-st.ProgressMs) * time.Millisecond
		if left <= 0 {
			return
		}

		// Последние секунды досыпаем ровно, без промежуточных проверок.
		//
		// Иначе получается слышный ляп: мы узнаём о конце трека, только увидев
		// в Spotify уже следующий, — то есть следующий успевает секунду-другую
		// поиграть, и заказ его перебивает. А время конца известно точно, и
		// уснуть до него можно с точностью до миллисекунды.
		if left <= waitTail {
			p.log.Info("трек стримера доигрывает, заказ пойдёт сразу за ним",
				"трек", st.Item.Name, "осталось_мс", left.Milliseconds())
			p.napOrWake(ctx, left+settle)
			return
		}

		p.log.Debug("жду конца трека стримера",
			"трек", st.Item.Name, "осталось_мс", left.Milliseconds())

		if !told {
			told = true
			p.log.Info("заказ ждёт конца трека стримера",
				"заказ", item.Artist+" — "+item.Title,
				"трек_стримера", st.Item.Name, "осталось_мс", left.Milliseconds())
			if p.OnWaiting != nil {
				p.OnWaiting(item, left)
			}
		}

		// Всё, что раньше последних секунд, пережидаем одним сном: опрашивать
		// Spotify каждые две секунды все четыре минуты — тысяча запросов ни за чем.
		if !p.napOrWake(ctx, left-waitTail) {
			// Скип или остановка приложения — ждать больше нельзя.
			return
		}
	}
}

// napOrWake спит, но просыпается на скипе и на отмене.
//
// Скип во время ожидания означает «не жди, включай заказ»: это единственная
// кнопка, которой стример может поторопить очередь, и она обязана работать
// именно так, а не молча пропадать.
func (p *Player) napOrWake(ctx context.Context, d time.Duration) bool {
	timer := time.NewTimer(d)
	defer timer.Stop()

	select {
	case <-ctx.Done():
		return false
	case <-p.skip:
		p.log.Info("ожидание конца трека прервано скипом")
		return false
	case <-timer.C:
		return true
	}
}
